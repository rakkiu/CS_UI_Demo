// Run against the local Vite server. Supply PLAYWRIGHT_MODULE when using a bundled runtime.
import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, channel: process.env.BROWSER_CHANNEL || 'msedge' })
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:5173'
const out = path.join(os.tmpdir(), 'crabshare-investor-qa')
await mkdir(out, { recursive: true })
let checks = 0
const pass = message => { checks++; console.log(`PASS ${message}`) }
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, reducedMotion: 'reduce' })
  // Marketing font is external; Investor fonts are local. Keep tests independent of Google uptime.
  await context.route('https://fonts.googleapis.com/**', route => route.abort())
  const page = await context.newPage()
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  const go = async route => { await page.goto(base + route, { waitUntil: 'domcontentloaded' }); await page.locator('h1').waitFor() }
  const text = async (locator, expected) => assert.match(await locator.innerText(), expected)
  await go('/investor')
  await text(page.locator('h1'), /Không gian nhà đầu tư/)
  pass('Direct Investor route requires a demo session')
  await go('/')
  await page.getByRole('link', { name: 'Trải nghiệm Investor', exact: false }).click()
  await page.waitForURL('**/investor', { waitUntil: 'domcontentloaded' })
  await text(page.locator('h1'), /Chào Minh Anh/)
  assert.equal(await page.locator('.iv-sidebar').getByRole('link', { name: 'Bao tiêu', exact: true }).count(), 0)
  pass('Landing demo login enters Financial workspace with correct permissions')
  await page.screenshot({ path: path.join(out, 'overview-desktop.png'), fullPage: true })

  await go('/investor/batches')
  await page.getByRole('textbox', { name: 'Tìm Batch' }).fill('khong-ton-tai')
  await text(page.locator('.iv-empty'), /Chưa tìm thấy/)
  await page.getByRole('button', { name: 'Xóa bộ lọc' }).click()
  assert.equal(await page.locator('.iv-batch-card').count(), 5)
  pass('Batch search empty state and reset')

  await go('/investor/contribute?batch=CR-0926')
  const amount = page.getByRole('spinbutton', { name: 'Số tiền góp vốn (VND)' })
  await amount.fill('1')
  assert.equal(await amount.evaluate(e => e.validity.valid), false)
  await amount.fill('10000000')
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Xác nhận & giữ chỗ' }).click()
  await page.getByText('Thử tình huống khác').click()
  await page.getByRole('button', { name: 'Hết hạn giữ chỗ', exact: true }).click()
  await text(page.locator('.iv-note.warning'), /hết hạn/)
  await page.getByRole('button', { name: 'Xác nhận & giữ chỗ' }).click()
  await page.getByRole('button', { name: 'Mô phỏng đối soát thành công' }).click()
  await text(page.locator('.iv-success'), /Góp vốn thành công/)
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Tải biên nhận demo' }).click()
  assert.match((await download).suggestedFilename(), /bien-nhan/)
  await go('/investor/portfolio')
  await text(page.locator('.iv-table'), /10\.000\.000/)
  await page.reload({ waitUntil: 'domcontentloaded' })
  await text(page.locator('.iv-table'), /10\.000\.000/)
  pass('Contribution validation, expiry, reconciliation, receipt and reload persistence')

  await go('/investor/contracts')
  assert.equal(await page.getByRole('button', { name: 'Xác nhận ký trong demo' }).isDisabled(), true)
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Xác nhận ký trong demo' }).click()
  await text(page.locator('.iv-panel').last(), /Hồ sơ đã hoàn tất/)
  await page.locator('.iv-contract-list').getByRole('button', { name: /CR-0926/ }).click()
  assert.equal(await page.getByRole('button', { name: 'Chờ Operator ký trước' }).isDisabled(), true)
  pass('Contract consent required; Investor cannot sign before Operator')

  await go('/investor/profile?tab=kyc')
  await page.getByText('Thử luồng chưa xác minh').click()
  await page.getByRole('button', { name: 'Đặt lại trạng thái xác minh demo' }).click()
  await go('/investor/contribute?batch=CR-0926')
  await page.getByRole('link', { name: 'Hoàn tất xác minh', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: 'Bắt đầu xác minh demo' }).isDisabled(), true)
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Bắt đầu xác minh demo' }).click()
  await page.getByRole('button', { name: 'Mô phỏng kết quả đạt', exact: true }).click()
  await text(page.locator('.iv-success'), /Danh tính đã xác minh/)
  pass('KYC gates contribution and requires separate consent')

  await go('/investor/settlement?batch=CR-0526')
  await page.getByRole('button', { name: 'Gửi phản hồi về quyết toán' }).click()
  await page.getByRole('textbox', { name: 'Nội dung cần đối chiếu' }).fill('Vui lòng đối chiếu doanh thu bao tiêu của Batch này.')
  await page.getByRole('button', { name: 'Gửi phản hồi', exact: true }).click()
  await page.getByText('Trải nghiệm tình huống pool âm').click()
  await page.getByRole('checkbox').check()
  await text(page.locator('aside .iv-panel'), /26\.000\.000/)
  pass('Settlement feedback and capital-limited negative-pool illustration')
  await go('/investor/notifications')
  await page.getByRole('button', { name: 'Đánh dấu tất cả đã đọc' }).click()
  await page.getByRole('button', { name: /Chưa đọc/ }).click()
  await text(page.locator('.iv-empty'), /Bạn đã xem hết/)
  pass('Notifications unread filter and bulk-read state')
  await go('/investor/offtake/claim')
  await text(page.locator('h1'), /Chức năng dành cho Investor bao tiêu/)
  pass('Financial direct URL cannot access Offtake actions')

  await go('/dang-nhap?demo=offtake')
  await page.waitForURL('**/investor', { waitUntil: 'domcontentloaded' })
  await page.locator('.iv-sidebar').getByRole('link', { name: 'Bao tiêu', exact: true }).waitFor()
  await go('/investor/offtake/commit')
  await page.getByLabel('Bạn có phải Operator hoặc bên liên quan của Batch này?').selectOption('yes')
  assert.equal(await page.getByRole('button', { name: 'Gửi yêu cầu xét duyệt' }).isDisabled(), true)
  await page.getByLabel('Bạn có phải Operator hoặc bên liên quan của Batch này?').selectOption('no')
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Gửi yêu cầu xét duyệt' }).click()
  await text(page.locator('.iv-success'), /Đã gửi cam kết mẫu/)
  pass('Offtake inherits investment screens; related parties blocked from commitment')
  await go('/investor/offtake/claim')
  await page.getByText('Thử trạng thái hết hạn').click()
  await page.getByRole('checkbox', { name: 'Đóng cửa sổ ưu tiên trong bản demo' }).check()
  assert.equal(await page.getByRole('button', { name: 'Xác nhận & thanh toán demo' }).count(), 0)
  await page.getByRole('checkbox', { name: 'Đóng cửa sổ ưu tiên trong bản demo' }).uncheck()
  await page.getByRole('spinbutton').fill('30')
  await page.getByRole('checkbox', { name: /Tôi xác nhận khối lượng/ }).check()
  await page.getByRole('button', { name: 'Xác nhận & thanh toán demo' }).click()
  await text(page.locator('.iv-success'), /30 kg/)
  await go('/investor/deliveries')
  await page.getByRole('button', { name: 'Xác nhận đã nhận đủ hàng' }).click()
  await text(page.locator('.iv-panel').first(), /Đã nhận/)
  await go('/investor/offtake')
  await text(page.locator('.iv-stats'), /50 kg/)
  await go('/investor/portfolio')
  await text(page.locator('.iv-table'), /30\.000\.000/)
  pass('Priority expiry, separate purchase allocation, remaining quota and receipt confirmation')

  const routes = ['/investor', '/investor/batches', '/investor/batch?batch=CR-0926', '/investor/contribute?batch=CR-0926', '/investor/portfolio', '/investor/production?batch=CR-0826', '/investor/contracts', '/investor/settlements', '/investor/settlement?batch=CR-0526', '/investor/notifications', '/investor/profile', '/investor/offtake', '/investor/offtake/commit', '/investor/offtake/claim', '/investor/deliveries']
  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({ width, height: 900 })
    for (const route of routes) {
      await go(route)
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)
      assert.equal(overflow, false, `Viewport overflow at ${width}px: ${route}`)
    }
    await go('/investor')
    await page.screenshot({ path: path.join(out, `overview-${width}.png`), fullPage: true })
  }
  await page.getByRole('button', { name: 'Mở điều hướng Investor' }).click()
  assert.equal(await page.locator('.iv-sidebar').isVisible(), true)
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('.iv-sidebar').isVisible(), false)
  pass('All 15 routes render at 1440/390/320px without page overflow; mobile drawer/Escape work')
  await page.setViewportSize({ width: 1440, height: 1000 })
  for (const [route, name] of [['/investor/batches', 'batches'], ['/investor/contribute?batch=CR-0926', 'contribution'], ['/investor/settlement?batch=CR-0526', 'settlement'], ['/investor/offtake/claim', 'offtake-claim']]) {
    await go(route); await page.screenshot({ path: path.join(out, `${name}.png`), fullPage: true })
  }
  assert.deepEqual(errors, [], 'Browser runtime errors')
  pass('No browser runtime exceptions during tested flows')
  console.log(`Completed ${checks} checks. Screenshots: ${out}`)
} finally { await browser.close() }
